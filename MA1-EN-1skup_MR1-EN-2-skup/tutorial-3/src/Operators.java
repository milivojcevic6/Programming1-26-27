public class Operators {

    /*
    + - * / %
     */

    public static void basicOperators(){

//        int a = 7;
//        int b = 3;
        int a = 7, b = 3;

        System.out.println("a is: " + a);
        System.out.println("b is: " + b);

        System.out.println("a+b is: " + a + b );
        System.out.println("a+b is: " + (a + b) );
        System.out.println("a-b is: " + (a - b) );
        System.out.println("a*b is: " + (a * b) );
        System.out.println("a/b is: " + (a / b) );
        System.out.println("a/b is: " + ( (double) a / b) );
        System.out.println("a%b is: " + (a % b) );

    }
}
